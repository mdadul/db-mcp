#!/usr/bin/env node
import { randomBytes } from "node:crypto";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { loadEnvFile } from "node:process";
import { findClient, pickClient } from "./installClient.js";
import { VERSION } from "./version.js";

if (["--version", "-v"].includes(process.argv[2] ?? "")) {
  console.log(VERSION);
  process.exit(0);
}

// Fixed per-user location so a global/npx invocation never reads or clutters
// whatever directory the user happens to be in (override with DB_MCP_HOME).
const CONFIG_DIR = process.env.DB_MCP_HOME ?? join(homedir(), ".db-mcp");
const envPath = join(CONFIG_DIR, ".env");

if (!existsSync(envPath)) {
  mkdirSync(CONFIG_DIR, { recursive: true });
  const databasePath =
    process.env.DATABASE_PATH ?? join(CONFIG_DIR, "data", "db-mcp.sqlite");
  mkdirSync(dirname(databasePath), { recursive: true });
  const encryptionKey = randomBytes(32).toString("hex");
  const mcpToken = randomBytes(24).toString("base64url");

  writeFileSync(
    envPath,
    [
      "# Generated by db-mcp setup - do not commit this file",
      `DATABASE_PATH=${databasePath}`,
      `ENCRYPTION_KEY=${encryptionKey}`,
      `MCP_TOKEN=${mcpToken}`,
      "PORT=4080",
      "",
    ].join("\n"),
    { mode: 0o600 }
  );
  console.error(`Generated ${envPath}`);
  console.error(`Your MCP_TOKEN is stored in ${envPath} (never printed).`);
  console.error("Run `db-mcp install` to connect this to Claude, Cursor, Windsurf, opencode, or VS Code.");
}

try {
  loadEnvFile(envPath);
} catch (error) {
  console.error(`Could not read config file at ${envPath}:`);
  console.error((error as Error).message);
  console.error("Fix or delete this file, then try again.");
  process.exit(1);
}

const [command, clientId] = process.argv.slice(2);

if (command === "install") {
  await runInstall(clientId);
} else if (command === "stdio") {
  await import("./stdio.js");
} else {
  await import("./index.js");
}

async function runInstall(clientId: string | undefined): Promise<void> {
  const token = process.env.MCP_TOKEN;
  if (!token) {
    console.error(`MCP_TOKEN not found in ${envPath}. Delete that file and run db-mcp again to regenerate it.`);
    process.exit(1);
  }
  const port = process.env.PORT ?? "4080";

  try {
    const client = clientId ? findClient(clientId) : await pickClient();
    const message = client.install({
      serverName: "db-mcp",
      url: `http://localhost:${port}/mcp`,
      token,
    });
    console.log(`\n✓ ${client.label}: ${message}`);
  } catch (error) {
    console.error(`\nCouldn't configure that client: ${(error as Error).message}`);
    process.exit(1);
  }
}