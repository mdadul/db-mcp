type Palette = {
  background: string;
  surface: string;
  raised: string;
  sidebar: string;
  border: string;
  borderStrong: string;
  text: string;
  muted: string;
  subtle: string;
  accent: string;
  accentHover: string;
  accentSubtle: string;
  accentForeground: string;
  success: string;
  successSubtle: string;
  warning: string;
  warningSubtle: string;
  danger: string;
  dangerSubtle: string;
  info: string;
  infoSubtle: string;
  focus: string;
  chart: [string, string, string, string, string, string];
  syntax: ThemeVariant["syntax"];
};

const syntax = (
  keyword: string,
  string: string,
  number: string,
  comment: string,
  fn: string,
  operator: string,
  type: string,
  punctuation: string,
): ThemeVariant["syntax"] => ({
  keyword,
  string,
  number,
  comment,
  function: fn,
  operator,
  type,
  punctuation,
});
const variant = (palette: Palette): ThemeVariant => ({
  tokens: {
    background: palette.background,
    surface: palette.surface,
    "surface-raised": palette.raised,
    sidebar: palette.sidebar,
    border: palette.border,
    "border-strong": palette.borderStrong,
    text: palette.text,
    "text-muted": palette.muted,
    "text-subtle": palette.subtle,
    accent: palette.accent,
    "accent-hover": palette.accentHover,
    "accent-subtle": palette.accentSubtle,
    "accent-foreground": palette.accentForeground,
    success: palette.success,
    "success-subtle": palette.successSubtle,
    warning: palette.warning,
    "warning-subtle": palette.warningSubtle,
    danger: palette.danger,
    "danger-subtle": palette.dangerSubtle,
    info: palette.info,
    "info-subtle": palette.infoSubtle,
    "focus-ring": palette.focus,
  },
  chart: palette.chart,
  syntax: palette.syntax,
});

